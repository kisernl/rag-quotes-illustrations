#!/usr/bin/env python3
"""Regenerate COUNTS.md — the corpus tally for rag-quotes-illustrations.

Counts entries per doc and rolls them up by:
  - track:    quotes (docs/quotes/) vs. illustrations (docs/illustrations/)
  - leaning:  religious (`tradition` != "other") vs. secular ("other")

Entry counts: for docs/quotes files rendered from sources/quotes/*.jsonl
the record count is authoritative; otherwise `**N.**` enumerals and
`####` entry headings (the atomic units of anthology docs; the `#### Gold`
section label is excluded) are counted. Docs with neither show "—" and
contribute to doc totals but not entry totals.

Run after adding or re-rendering any doc:
    python3 tools/update_counts.py
"""
import re
from datetime import date
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
DOC = REPO / 'docs'
JSONL_DIR = REPO / 'sources' / 'quotes'
OUT = REPO / 'COUNTS.md'

TRACK = {'quotes': 'quotes', 'illustrations': 'illustrations'}
TRACK_ORDER = ['quotes', 'illustrations']

FM_FIELD = re.compile(r'^(\w+):\s*(.*)$')
ENUMERAL = re.compile(r'^\*\*\d+\.\*\*', re.M)
ENTRY_HEAD = re.compile(r'^#### (?!Gold\b)', re.M)


def frontmatter(text):
    if not text.startswith('---'):
        return {}
    block = text.split('---', 2)[1]
    return {m.group(1): m.group(2).strip().strip('"')
            for line in block.splitlines()
            if (m := FM_FIELD.match(line))}


def entry_count(path, text):
    jsonl = JSONL_DIR / f'{path.stem}.jsonl'
    if jsonl.exists():
        return sum(1 for _ in jsonl.open())
    n = len(ENUMERAL.findall(text)) + len(ENTRY_HEAD.findall(text))
    return n if n else None


def main():
    docs = []
    for p in sorted(DOC.rglob('*.md')):
        text = p.read_text()
        fm = frontmatter(text)
        track = TRACK.get(p.parent.name, p.parent.name)
        docs.append({
            'path': p.relative_to(DOC),
            'track': track,
            'secular': fm.get('tradition') == 'other',
            'entries': entry_count(p, text),
        })

    tally = {t: {'rel': 0, 'sec': 0, 'unknown': 0}
             for t in TRACK_ORDER}
    for d in docs:
        t = tally.setdefault(d['track'], {'rel': 0, 'sec': 0,
                                          'unknown': 0})
        if d['entries'] is None:
            t['unknown'] += 1
        elif d['secular']:
            t['sec'] += d['entries']
        else:
            t['rel'] += d['entries']

    lines = [
        '# Corpus Counts',
        '',
        'Tallies for the rag-quotes-illustrations corpus, generated by '
        '`tools/update_counts.py` — **do not hand-edit; re-run the script '
        'after adding or re-rendering content.**',
        '',
        f'Last run: {date.today().isoformat()}',
        '',
        '## Entry tallies',
        '',
        'Religious = `tradition` other than `other`; secular = '
        '`tradition: "other"`. Track = the `docs/` subdirectory '
        '(path-derived `form`).',
        '',
        '| track | religious | secular | total |',
        '|---|---|---|---|',
    ]
    tr = ts = 0
    for t in TRACK_ORDER:
        v = tally.get(t, {'rel': 0, 'sec': 0})
        lines.append(f"| {t} | {v['rel']} | {v['sec']} | "
                     f"{v['rel'] + v['sec']} |")
        tr += v['rel']
        ts += v['sec']
    lines += [
        f'| **total** | **{tr}** | **{ts}** | **{tr + ts}** |',
        '',
        '## Per-document',
        '',
        '| doc | track | tradition leaning | entries |',
        '|---|---|---|---|',
    ]
    for d in docs:
        leaning = 'secular' if d['secular'] else 'religious'
        n = d['entries'] if d['entries'] is not None else '—'
        lines.append(f"| {d['path']} | {d['track']} | {leaning} | {n} |")
    uncounted = [d for d in docs if d['entries'] is None]
    if uncounted:
        lines += ['',
                  f'_{len(uncounted)} doc(s) have no countable entries '
                  '(no `**N.**` enumerals or `####` entry headings) — '
                  'counted in the doc list but not the entry tally._']
    lines.append('')
    OUT.write_text('\n'.join(lines))
    print(f'wrote {OUT}: {tr} religious + {ts} secular entries '
          f'across {len(docs)} docs')


if __name__ == '__main__':
    main()
